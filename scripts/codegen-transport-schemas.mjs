#!/usr/bin/env node
/**
 * Generate TypeScript types from the pinned ohho-os JSON schemas (vendor/).
 *
 *   node scripts/codegen-transport-schemas.mjs          # write
 *   node scripts/codegen-transport-schemas.mjs --check  # exit 1 if stale
 */

import { compileFromFile } from "json-schema-to-typescript";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const VENDOR = path.join(ROOT, "packages/schemas/vendor/ohho-os");
const OUT_DIR = path.join(ROOT, "packages/schemas/src/generated");
const OUT_FILE = path.join(OUT_DIR, "transport.generated.ts");
const PROTOCOL_FILE = path.join(ROOT, "packages/schemas/src/protocol-version.generated.ts");

const check = process.argv.includes("--check");

async function loadManifest() {
  const raw = await readFile(path.join(VENDOR, "manifest.json"), "utf8");
  return JSON.parse(raw);
}

async function buildGeneratedBody(manifest) {
  const chunks = [
    "/* eslint-disable */",
    "/**",
    " * @generated by scripts/codegen-transport-schemas.mjs — do not edit.",
    ` * Pinned protocol ${manifest.protocolVersion} (ohho-os ${manifest.ohhoOsVersion}).`,
    " */",
    "",
  ];

  const seen = new Set();
  const schemaFiles = Object.values(manifest.schemas).sort();
  for (const file of schemaFiles) {
    const schemaPath = path.join(VENDOR, file);
    const ts = await compileFromFile(schemaPath, {
      bannerComment: "",
      additionalProperties: false,
      enableConstEnums: true,
    });
    const parts = ts.trim().split(/\n(?=export )/);
    for (const block of parts) {
      const match = block.match(/^export (?:type|interface) (\w+)/);
      if (match) {
        if (seen.has(match[1])) {
          continue;
        }
        seen.add(match[1]);
      }
      chunks.push(block.trimEnd(), "");
    }
  }

  return chunks.join("\n");
}

async function buildProtocolVersionModule(manifest) {
  return `/* eslint-disable */
/** @generated by scripts/codegen-transport-schemas.mjs — do not edit. */
export const PINNED_PROTOCOL_VERSION = "${manifest.protocolVersion}";
export const PINNED_OHHO_OS_VERSION = "${manifest.ohhoOsVersion}";
`;
}

async function writeOrCheck(filePath, content) {
  if (check) {
    let existing = "";
    try {
      existing = await readFile(filePath, "utf8");
    } catch {
      console.error(`missing ${path.relative(ROOT, filePath)} — run codegen`);
      return false;
    }
    if (existing !== content) {
      console.error(`stale ${path.relative(ROOT, filePath)} — run npm run codegen:schemas`);
      return false;
    }
    return true;
  }
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, content, "utf8");
  return true;
}

async function main() {
  const manifest = await loadManifest();
  const transportBody = await buildGeneratedBody(manifest);
  const protocolBody = await buildProtocolVersionModule(manifest);

  const okTransport = await writeOrCheck(OUT_FILE, transportBody);
  const okProtocol = await writeOrCheck(PROTOCOL_FILE, protocolBody);

  if (!check) {
    console.log(`wrote ${path.relative(ROOT, OUT_FILE)}`);
    console.log(`wrote ${path.relative(ROOT, PROTOCOL_FILE)}`);
  }

  if (!okTransport || !okProtocol) {
    process.exit(1);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
